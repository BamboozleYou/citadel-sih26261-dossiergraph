"""Secure viewing: originals never leave the server. Pages are rasterised, evidence
boxes drawn on top, and every image carries a watermark naming the viewer and time."""
from __future__ import annotations

import datetime as dt
import io

import fitz
from PIL import Image, ImageDraw, ImageFont

from . import crypto

SEV_COLOR = {"high": (192, 57, 43), "medium": (217, 154, 0), "low": (31, 95, 173), "info": (107, 114, 128)}
DPI = 110


def _font(size: int):
    for p in ("/System/Library/Fonts/Supplemental/Arial.ttf", "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"):
        try:
            return ImageFont.truetype(p, size)
        except OSError:
            continue
    return ImageFont.load_default()


def _page_image(doc_id: str, page: int, mime_pdf: bool) -> tuple[Image.Image, float]:
    data = crypto.load(doc_id)
    if not mime_pdf:
        return Image.open(io.BytesIO(data)).convert("RGB"), 1.0
    doc = fitz.open(stream=data, filetype="pdf")
    page = max(0, min(page, len(doc) - 1))
    pix = doc[page].get_pixmap(dpi=DPI)
    return Image.frombytes("RGB", (pix.width, pix.height), pix.samples), DPI / 72.0


def watermark(img: Image.Image, viewer: str) -> Image.Image:
    stamp = f"{viewer} · {dt.datetime.now():%d-%m-%Y %H:%M} · CONFIDENTIAL · DossierGraph"
    layer = Image.new("RGBA", img.size, (0, 0, 0, 0))
    d = ImageDraw.Draw(layer)
    f = _font(max(14, img.width // 45))
    tw = d.textlength(stamp, font=f)
    tile = Image.new("RGBA", (int(tw) + 60, f.size + 20), (0, 0, 0, 0))
    ImageDraw.Draw(tile).text((10, 5), stamp, font=f, fill=(27, 42, 74, 38))
    tile = tile.rotate(28, expand=True)
    for y in range(-tile.height, img.height + tile.height, int(tile.height * 0.9)):
        for x in range(-tile.width // 2, img.width, tile.width):
            layer.alpha_composite(tile, (max(0, x + (y // 7) % 200), max(0, y)))
    return Image.alpha_composite(img.convert("RGBA"), layer).convert("RGB")


def render_page(doc_id: str, page: int, boxes: list[dict], viewer: str, mime_pdf: bool = True) -> bytes:
    img, s = _page_image(doc_id, page, mime_pdf)
    d = ImageDraw.Draw(img, "RGBA")
    for b in boxes:
        if b.get("page", 0) != page or not b.get("bbox"):
            continue
        x0, y0, x1, y1 = [v * s for v in b["bbox"]]
        col = SEV_COLOR.get(b.get("severity", "medium"), (217, 154, 0))
        d.rectangle((x0 - 4, y0 - 3, x1 + 4, y1 + 3), outline=col + (255,), width=3, fill=col + (40,))
    img = watermark(img, viewer)
    bio = io.BytesIO()
    img.save(bio, format="PNG", optimize=True)
    return bio.getvalue()


def evidence_crop(doc_id: str, page: int, bbox, viewer: str, severity: str, mime_pdf: bool = True) -> bytes:
    img, s = _page_image(doc_id, page, mime_pdf)
    x0, y0, x1, y1 = [v * s for v in bbox]
    box = (int(max(0, x0 - 230 * s)), int(max(0, y0 - 22 * s)), int(min(img.width, x1 + 60 * s)), int(min(img.height, y1 + 22 * s)))
    d = ImageDraw.Draw(img, "RGBA")
    col = SEV_COLOR.get(severity, (217, 154, 0))
    d.rectangle((x0 - 4, y0 - 3, x1 + 4, y1 + 3), outline=col + (255,), width=3, fill=col + (35,))
    crop = watermark(img.crop(box), viewer)
    bio = io.BytesIO()
    crop.save(bio, format="PNG")
    return bio.getvalue()


def scrutiny_pdf(a: dict, report: dict, docs: list[dict], finds: list[dict], decisions: list[dict],
                 audit_head: str, viewer_name: str, nice_map: dict) -> bytes:
    """Generate a printable AICTE Pre-Scrutiny & EVC Verification Note PDF."""
    from reportlab.lib.colors import HexColor
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.units import mm
    from reportlab.pdfgen import canvas

    buf = io.BytesIO()
    W, H = A4
    c = canvas.Canvas(buf, pagesize=A4)
    c.setTitle(f"DossierGraph Scrutiny Note - {a['id']}")
    c.setAuthor("DossierGraph Decision Support")

    def header():
        c.setFillColor(HexColor("#1b2a4a"))
        c.rect(0, H - 24 * mm, W, 24 * mm, stroke=0, fill=1)
        c.setFillColor(HexColor("#ffffff"))
        c.setFont("Helvetica-Bold", 13)
        c.drawString(16 * mm, H - 11 * mm, "AICTE PRE-SCRUTINY & EVC VERIFICATION NOTE (DECISION SUPPORT)")
        c.setFont("Helvetica", 8.5)
        c.drawString(16 * mm, H - 18 * mm, f"DossierGraph · Application {a['id']} · Rule Pack {report.get('rules_version', 'APH-2024-27')} · Generated by {viewer_name}")
        return H - 32 * mm

    y = header()

    def need(space_mm: float):
        nonlocal y
        if y < space_mm * mm:
            c.showPage()
            y = header()

    # Institution summary block
    c.setFillColor(HexColor("#1f2937"))
    c.setFont("Helvetica-Bold", 12)
    c.drawString(16 * mm, y, f"{a['name']} ({a['inst_id']})")
    y -= 5.5 * mm
    c.setFont("Helvetica", 9)
    c.drawString(16 * mm, y, f"State / Region: {a['state']} ({a['region']})   ·   Status: {a['status']}   ·   Triage Score: {int(a['score'] or 0)}")
    y -= 4.8 * mm
    c.setFillColor(HexColor("#6b7280"))
    c.setFont("Helvetica", 8)
    c.drawString(16 * mm, y, f"Audit Chain Head SHA-256: {audit_head[:48]}...")
    y -= 7 * mm

    # 1. Documents
    c.setFillColor(HexColor("#1b2a4a"))
    c.setFont("Helvetica-Bold", 10.5)
    c.drawString(16 * mm, y, "1. Document Authentication & Issuer Verification Summary")
    y -= 5 * mm
    c.setFont("Helvetica-Bold", 8.5)
    c.setFillColor(HexColor("#4b5563"))
    c.drawString(16 * mm, y, "Document Type")
    c.drawString(78 * mm, y, "Filename / Mode")
    c.drawString(138 * mm, y, "Status")
    c.drawString(170 * mm, y, "SHA-256")
    y -= 2 * mm
    c.setStrokeColor(HexColor("#d1d5db"))
    c.line(16 * mm, y, W - 16 * mm, y)
    y -= 4.5 * mm
    c.setFont("Helvetica", 8.5)
    for d in docs:
        need(22)
        c.setFillColor(HexColor("#1f2937"))
        c.drawString(16 * mm, y, nice_map.get(d["doc_type"], d["doc_type"])[:30])
        c.drawString(78 * mm, y, f"{d['filename'][:22]} ({d['mode']})")
        st = d["status"].upper().replace("_", " ")
        c.setFillColor(HexColor("#c0392b") if d["status"] == "mismatch" else (HexColor("#2e8b57") if d["status"] == "verified" else HexColor("#6b7280")))
        c.drawString(138 * mm, y, st[:16])
        c.setFillColor(HexColor("#6b7280"))
        c.drawString(170 * mm, y, d["sha256"][:10])
        y -= 4.6 * mm
    y -= 4 * mm

    # 2. Findings
    need(35)
    c.setFillColor(HexColor("#1b2a4a"))
    c.setFont("Helvetica-Bold", 10.5)
    c.drawString(16 * mm, y, f"2. Scrutiny Findings & APH 2024-27 Clause Citations ({len(finds)})")
    y -= 5.5 * mm
    if not finds:
        c.setFont("Helvetica", 9)
        c.setFillColor(HexColor("#2e8b57"))
        c.drawString(16 * mm, y, "Nil deficiencies detected across automated checks.")
        y -= 6 * mm
    for i, f in enumerate(finds, 1):
        need(28)
        sev = f["severity"].upper()
        clause = f" · APH {f['aph_ref']}" if f.get("aph_ref") else ""
        st_lbl = f" [{f['state'].upper()} by {f['officer']}]" if f.get("state") and f["state"] != "open" else " [OPEN]"
        c.setFont("Helvetica-Bold", 9)
        c.setFillColor(HexColor("#c0392b") if f["severity"] == "high" else (HexColor("#9a6a00") if f["severity"] == "medium" else HexColor("#1f5fad")))
        c.drawString(16 * mm, y, f"{i}. [{sev} / {f['category'].upper()}{clause}] {f['title'][:68]}{st_lbl}")
        y -= 4.3 * mm
        c.setFont("Helvetica", 8.3)
        c.setFillColor(HexColor("#1f2937"))
        c.drawString(20 * mm, y, (f.get("detail") or "")[:105])
        y -= 4.0 * mm
        if f.get("suggestion"):
            c.setFillColor(HexColor("#4b5563"))
            c.drawString(20 * mm, y, f"Action: {f['suggestion'][:100]}")
            y -= 4.0 * mm
        if f.get("reason"):
            c.setFillColor(HexColor("#6a4c93"))
            c.drawString(20 * mm, y, f"Officer review note: {f['reason'][:95]}")
            y -= 4.0 * mm
        y -= 1.5 * mm
    y -= 3 * mm

    # 3. EVC On-Site Verification List
    need(35)
    c.setFillColor(HexColor("#1b2a4a"))
    c.setFont("Helvetica-Bold", 10.5)
    c.drawString(16 * mm, y, "3. Expert Visit Committee (EVC) Physical Verification List")
    y -= 5 * mm
    c.setFont("Helvetica", 8.5)
    c.setFillColor(HexColor("#1f2937"))
    for r in report.get("checklist", []):
        need(18)
        c.drawString(18 * mm, y, f"[ ] {r['title']} ({r.get('aph_ref', '')}) — {r.get('on_fail', '')[:70]}")
        y -= 4.5 * mm
    for d in docs:
        if d["status"] in ("pending", "source_unavailable", "manual_review") and d["doc_type"] != "photo":
            need(18)
            c.drawString(18 * mm, y, f"[ ] Verify original physical document: {nice_map.get(d['doc_type'], d['doc_type'])} (status: {d['status']})")
            y -= 4.5 * mm
    y -= 4 * mm

    # 4. Decisions & Four-Eyes Sign-off
    need(30)
    c.setFillColor(HexColor("#1b2a4a"))
    c.setFont("Helvetica-Bold", 10.5)
    c.drawString(16 * mm, y, "4. Officer Decisions & Four-Eyes Approval Log")
    y -= 5 * mm
    c.setFont("Helvetica", 8.5)
    c.setFillColor(HexColor("#1f2937"))
    if not decisions:
        c.drawString(18 * mm, y, "No formal decision recorded yet.")
        y -= 5 * mm
    for d in decisions:
        need(18)
        appr = f" · {d['state']} by {d['approved_by']} ({d['approved_at']})" if d.get("approved_by") else f" · {d['state']}"
        c.drawString(18 * mm, y, f"• {d['action']} — proposed by {d['proposed_by']} ({d['proposed_at']}){appr}")
        y -= 4.2 * mm
        c.setFillColor(HexColor("#4b5563"))
        c.drawString(22 * mm, y, f"Reason: {d['reason'][:95]}")
        c.setFillColor(HexColor("#1f2937"))
        y -= 4.8 * mm

    c.setFillColor(HexColor("#6b7280"))
    c.setFont("Helvetica-Oblique", 7.5)
    c.drawString(16 * mm, 12 * mm, "Statutory Note: All DossierGraph outputs are advisory decision support. Final regulatory decisions vest with competent AICTE authorities.")
    c.showPage()
    c.save()
    return buf.getvalue()

